#!/usr/bin/env python3
"""Extract SpriteWorldX function prototypes from the public headers for Ghidra.

Writes tools/ghidra/prototypes_swx.h. Types are reduced to names that types.txt defines,
anything unknown (SDL types etc.) becomes void *.
"""
import os, re, glob
ROOT = os.path.join(os.path.dirname(__file__), "..")
HDRS = glob.glob(os.path.join(ROOT, "third_party/SpriteWorldX/Headers/*.h")) + \
       glob.glob(os.path.join(ROOT, "third_party/SpriteWorldX/Utils/*.h")) + \
       glob.glob(os.path.join(ROOT, "third_party/SpriteWorldX/BlitKernel/BlitKernel.h"))
KNOWN = {"void", "char", "short", "int", "long", "float", "double", "unsigned", "signed", "const",
         "SpriteWorldPtr", "SpriteLayerPtr", "SpritePtr", "FramePtr", "DrawDataPtr", "TileMapStructPtr",
         "SWRect", "SWRectPtr", "SWPoint", "SWBoolean", "SWError", "SWMovementType", "SDL_bool",
         "FrameProcPtr", "DrawProcPtr", "MoveProcPtr", "CollideProcPtr", "CallBackPtr",
         "WorldMoveProcPtr", "SpriteCompareProcPtr", "SDL_Surface", "SDL_Color", "uchar", "ushort", "uint"}
PTR_TD = {"FrameProcPtr", "DrawProcPtr", "MoveProcPtr", "CollideProcPtr", "CallBackPtr",
          "WorldMoveProcPtr", "SpriteCompareProcPtr"}

def norm_type(t):
    t = re.sub(r"\bSW_FUNC\b|\bextern\b|\bstatic\b|\binline\b|\bconst\b", "", t).strip()
    stars = t.count("*")
    base = t.replace("*", "").strip()
    base = re.sub(r"\s+", " ", base)
    base = {"unsigned long": "uint", "long": "int", "unsigned short": "ushort", "unsigned char": "uchar",
            "unsigned int": "uint", "unsigned": "uint", "SWStr255": "char *", "Uint32": "uint",
            "Uint8": "uchar", "Uint16": "ushort", "Sint16": "short", "Sint32": "int"}.get(base, base)
    if base in PTR_TD:
        base += "_t"
    elif base.split()[-1] not in KNOWN and not base.endswith("*"):
        return "void *" + "*" * max(0, stars - 1)
    return base + (" " + "*" * stars if stars else "")

out = []
seen = set()
for h in sorted(HDRS):
    src = open(h, encoding="latin1").read()
    src = re.sub(r"/\*.*?\*/", "", src, flags=re.S)
    src = re.sub(r"//[^\n]*", "", src)
    src = re.sub(r"^\s*#.*$", "", src, flags=re.M)
    for m in re.finditer(r"([A-Za-z_][\w\s\*]*?)\b(SW\w+|BK\w+)\s*\(([^;{)]*)\)\s*;", src, re.S):
        ret, name, params = m.group(1), m.group(2), m.group(3)
        if "typedef" in ret or name in seen:
            continue
        ret = ret.strip().split("\n")[-1]
        plist = []
        params = params.strip()
        if params and params != "void":
            for i, p in enumerate(params.split(",")):
                p = re.sub(r"\s+", " ", p.strip())
                pm = re.match(r"(.*?)(\w+)\s*(\[\s*\])?$", p)
                if not pm:
                    break
                ptype, pname = pm.group(1), pm.group(2)
                if not ptype.strip():
                    ptype, pname = pname, f"p{i}"
                if pm.group(3):
                    ptype += "*"
                plist.append(f"{norm_type(ptype)} {pname}")
            else:
                pass
        seen.add(name)
        out.append(f"{norm_type(ret)} {name}({', '.join(plist) if plist else 'void'});")
dst = os.path.join(ROOT, "tools/ghidra/prototypes_swx.h")
open(dst, "w").write("// Generated by tools/gen_swx_prototypes.py from public SpriteWorldX headers.\n" + "\n".join(out) + "\n")
print(len(out), "prototypes ->", dst)
