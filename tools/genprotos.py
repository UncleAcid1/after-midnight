#!/usr/bin/env python3
"""Writes src/game/MMGameProtos.h: prototypes for every non-static function defined in
src/game/*.c that no other header declares. Re-run after adding functions."""
import re, glob, os

ROOT = os.path.join(os.path.dirname(__file__), "..", "src")
OUT = os.path.join(ROOT, "game", "MMGameProtos.h")
headers = [h for h in glob.glob(ROOT + "/game/*.h") + glob.glob(ROOT + "/swx/*.h") if not h.endswith("MMGameProtos.h")]
declared = set()
for h in headers:
    for m in re.finditer(r"\b(\w+)\s*\(", open(h, errors="ignore").read()):
        declared.add(m.group(1))

defn = re.compile(r"^(?!static\b|typedef\b|return\b|else\b|if\b|for\b|while\b|switch\b)([A-Za-z_][\w \t\*]*?)\b(\w+)\s*\(", re.M)
out = ["// Generated by tools/genprotos.py from the definitions in src/game/*.c. Do not edit.",
       "#ifndef MMGAMEPROTOS_H", "#define MMGAMEPROTOS_H", ""]
for path in sorted(glob.glob(ROOT + "/game/*.c")):
    text = open(path, errors="ignore").read()
    protos = []
    for m in defn.finditer(text):
        name = m.group(2)
        if name in declared or name == "main":
            continue
        # find matching paren
        i = m.end() - 1
        depth = 0
        while i < len(text):
            if text[i] == "(":
                depth += 1
            elif text[i] == ")":
                depth -= 1
                if depth == 0:
                    break
            i += 1
        rest = text[i + 1:i + 40].lstrip()
        if not rest.startswith("{"):
            continue
        sig = text[m.start():i + 1]
        sig = re.sub(r"\s+", " ", sig).strip()
        protos.append(sig + ";")
        declared.add(name)
    if protos:
        out.append("// " + os.path.basename(path))
        out.extend(protos)
        out.append("")
out.append("#endif")
open(OUT, "w").write("\n".join(out) + "\n")
print("wrote", OUT, sum(1 for l in out if l.endswith(";")), "prototypes")
